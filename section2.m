function y = section2(x)
if x >= 0 & x < pi/6
    y=1;
end
if x >= pi/6 & x < pi/3
    y=2;
end
if x >= pi/3 & x < pi/2
    y=3;
end
if x >= pi/2 & x < 2*pi/3
    y=4;
end
if x >= 2*pi/3 & x < 5*pi/6
    y=5;
end
if x >= 5*pi/6 & x < pi
    y=6;
end
if x >= pi & x < 7*pi/6
    y=7;
end
if x >= 7*pi/6 & x < 8*pi/6
    y=8;
end
if x >= 8*pi/6 & x < 9*pi/6
    y=9;
end
if x >= 9*pi/6 & x < 10*pi/6
    y=10;
end
if x >= 10*pi/6 & x < 11*pi/6
    y=11;
end
if x >= 11*pi/6 & x < 2*pi
    y=12;
end
     
